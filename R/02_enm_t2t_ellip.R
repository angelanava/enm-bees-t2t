# ============================================================
# Bee Ecological Niche Modeling: MVE Model Calibration
# ============================================================
#
# Authors:Angela Nava-Bolaños, Luis Osorio-Olvera and Jorge Soberón
#
# Description:
# Calibrates ecological niche models using minimum-volume
# ellipsoids (MVEs) in multidimensional environmental space.
# For each species, the script selects environmental predictors
# based on correlation, partitions occurrence records into
# training and testing datasets, and fits candidate ellipsoids
# using different combinations of environmental variables.
## The selected ellipsoid is then projected onto geographic
# space to generate continuous suitability and binary
# potential distribution maps.
#
# Input:
#   - Species-specific occurrence and background SWD files
#     generated by enm_t2t_occs.R
#   - Environmental raster layers (.tif)
#
# Output:
#   - Model selection tables
#   - Training and testing datasets
#   - Continuous and binary raster projections
#
# Main package: ntbox
# ============================================================
#################

library(ntbox)
library(raster)
library(dplyr)
library(furrr) 
library(maptools)

rm(list = ls())

#Set work directory
setwd("C:/Users/enm_bees")

# Load species-specific occurrence and background datasets
occ_path <- list.files("occs_bg",pattern = "_occ_",full.names = T)
bg_path <- list.files("occs_bg",pattern = "_bg_",full.names = T)
# Load environmental rasters for model projection.
cp <- list.files("D:/Bios/5km/t2t_Am",pattern = ".tif$",full.names = TRUE,recursive = T)
capas <- raster::stack(cp)

if(!dir.exists("modelos")) dir.create("modelos")
if(!dir.exists("modelos/binarios")) dir.create("modelos/binarios")
if(!dir.exists("modelos/continuos")) dir.create("modelos/continuos")
if(!dir.exists("resultados_seleccion")) dir.create("resultados_seleccion")
if(!dir.exists("datos_train_test")) dir.create("datos_train_test")

rr <- seq_along(occ_path) %>% purrr::map_df(function(x){
  d <- rio::import(occ_path[x])
  bg <- rio::import(bg_path[x])
  excluir<-which(names(d) %in% c("sp_name","x","y","roads"))
  # Remove highly correlated environmental predictors (r = 0.7)
  cor_mat <- cor(d[,-c(excluir)],use = "na.or.complete")
  cf <- correlation_finder(cor_mat = cor_mat,threshold = 0.7,verbose = FALSE)
  dn <- d[,c("sp_name","x","y",cf$descriptors,"roads")]
  dn <- na.omit(dn)
  bg <- na.omit(bg[,c("x","y","roads",cf$descriptors)])
  nbg <- nrow(bg)
  if(nbg> 50000){
    nsamps <- 50000
  } else{
    nsamps <- nbg
  }
  # Set the random seed for reproducible sampling
  set.seed(123)
  
  n_train <- ceiling(nrow(dn)*0.7)
  # Calculate road-based sampling weights for occurrences and background
  road_pre <- max(dn$roads) - dn$roads 
  ppp <- road_pre/sum(road_pre)
  ids_0 <- which(ppp==0)
  road_bg <- max(bg$roads) - bg$roads
  ppp_bg <- road_bg/sum(road_bg)
  ids_0_bg <- which(ppp_bg==0)
  
  #n_train
  if(length(ids_0)>0){
    pp_val <- min(ppp[-ids_0])
    ppp <- ifelse(ppp==0,pp_val,ppp)
  }
  if(length(ids_0_bg)>0){
    pp_val_bg <- min(ppp_bg[-ids_0_bg])
    ppp_bg <- ifelse(ppp_bg==0,pp_val_bg,ppp_bg)
  }
  bgID <- sample(nbg,nsamps,prob = ppp_bg)
  trainId <- sample(nrow(dn),n_train,prob =ppp)
  train <- dn[trainId,]
  test <- dn[-trainId,]
  
  if(nrow(train)>6){
    
    r0 <- try({
      if(length(cf$descriptors) > 16){
        nvar <- 3 
      } else {
        nvar <- 3:6
      }
      
      # Calibrate and evaluate candidate minimum-volume ellipsoid models
      ell_select <- ntbox::ellipsoid_selection(env_train = train,
                                               env_test = test,
                                               env_vars = cf$descriptors,
                                               nvarstest = nvar,
                                               level = 0.975,
                                               mve = TRUE,
                                               env_bg = bg[bgID,],
                                               omr_criteria = 0.1,
                                               parallel = T,
                                               ncores = 20,
                                               comp_each = 100,
                                               proc = TRUE,
                                               sub_sample = TRUE,
                                               sub_sample_size = 1000,
                                               proc_iter = 100,
                                               rseed = 123)
      sp_name <- gsub(" ","_",train$sp_name[1])
      rio::export(train,file = file.path("datos_train_test",
                                         paste0(sp_name,"_train.csv")))
      rio::export(test,file = file.path("datos_train_test",
                                        paste0(sp_name,"_test.csv")))
      
      ell_select <- ell_select %>% dplyr::filter(om_rate_train <= 0.075 & 
                                                   om_rate_test <= 0.05)%>% 
        dplyr::arrange(dplyr::desc(env_bg_auc))
      eselection <- ell_select %>% dplyr::filter(om_rate_train <= 0.075 & 
                                                   om_rate_test <= 0.05) %>% 
        dplyr::arrange(desc(env_bg_auc))
      if(nrow(eselection)>0){
        best_mod <- eselection[1,]
      } else{
        best_mod <- ell_select[1,]
      }
      
      vars <- stringr::str_split(best_mod$fitted_vars,",")[[1]]
      ccent <- cov_center(train[,vars],level = 0.975,vars = vars)
      suits <- round(exp(-0.5*mahalanobis(x = train[,vars], #para convertir distancia en idoneidad
                                          center = ccent$centroid,
                                          cov = ccent$covariance)),4)  %>% na.omit()
      
      suits <- sort(suits)
      tenId <- ceiling(nrow(train)*0.1)
      umbral <- suits[tenId] # Calculate the 10th-percentile training suitability threshold
      ncapas <- raster::stack(capas[[vars]])
      mod <-   ntbox::ellipsoidfit(envlayers = ncapas,
                                   centroid = ccent$centroid,
                                   covar = ccent$covariance,
                                   level = 0.9999,
                                   plot = FALSE,size = 3)
      mod_bin <- mod$suitRaster > umbral
      
      continuo <- file.path("modelos/continuos",paste0(sp_name,"_conti.tif"))
      binario <- file.path("modelos/binarios",paste0(sp_name,"_bin.tif"))
      rio::export(ell_select[,-c(4,6)],paste0("resultados_seleccion/",sp_name,".csv"))
      # Export continuous and binary model projections
      raster::writeRaster(mod$suitRaster,continuo,overwrite=T)
      raster::writeRaster(mod_bin,binario,overwrite=T)
      
    },silent = TRUE)
    print(x) 
    raster::removeTmpFiles(h=0.05)
    if(exists("mod")) return(best_mod)
  }
  return()
})

